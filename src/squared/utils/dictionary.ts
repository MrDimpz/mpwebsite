export const CORE_DICTIONARY: Set<string> = new Set(
  CORE_WORD_STRING
    .trim()
    .split(/\s+/)
    .map((w) => w.toUpperCase().replace(/[^A-Z]/g, ''))
    .filter((w) => w.length >= 4)
);

// Build a Prefix Set (Trie equivalent) for ultra-fast O(1) prefix pruning during DFS solving
export const CORE_PREFIXES: Set<string> = new Set();
for (const word of CORE_DICTIONARY) {
  for (let i = 1; i <= word.length; i++) {
    CORE_PREFIXES.add(word.slice(0, i));
  }
}

// Local definition cache so repeated inspections are 0ms
const definitionCache = new Map<string, WordDefinition>();

// Curated fallback descriptions when offline or for common puzzle terms
function getCuratedFallback(word: string): WordDefinition {
  const lower = word.toLowerCase();
  let pos = 'noun / verb';
  if (lower.endsWith('ly')) pos = 'adverb';
  else if (lower.endsWith('ing')) pos = 'verb (participle)';
  else if (lower.endsWith('ed')) pos = 'verb (past tense)';
  else if (lower.endsWith('ness') || lower.endsWith('tion') || lower.endsWith('ment')) pos = 'noun';
  else if (lower.endsWith('ful') || lower.endsWith('ous') || lower.endsWith('ive')) pos = 'adjective';

  return {
    word: word.toUpperCase(),
    partOfSpeech: pos,
    definition: `A recognized ${word.length}-letter English word uncovered on the puzzle board.`,
    source: 'curated',
  };
}

/**
 * Queries the fast Dictionary API (dictionaryapi.dev with Datamuse fallback)
 * to retrieve rich definitions and verify bonus words.
 */
export async function fetchWordDefinition(rawWord: string): Promise<WordDefinition | null> {
  const word = rawWord.trim().toUpperCase();
  if (definitionCache.has(word)) {
    return definitionCache.get(word)!;
  }

  // 1. Try Free Dictionary API (fast CDN-backed JSON endpoint)
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2800);
    const res = await fetch(`https://api.dictionaryapi.dev/api/v2/entries/en/${word.toLowerCase()}`, {
      signal: controller.signal,
    });
    clearTimeout(timeout);

    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        const entry = data[0];
        const meaning = entry.meanings?.[0];
        const defObj = meaning?.definitions?.[0];
        if (defObj?.definition) {
          const result: WordDefinition = {
            word,
            phonetic: entry.phonetic || entry.phonetics?.find((p: { text?: string }) => p.text)?.text,
            partOfSpeech: meaning.partOfSpeech || 'word',
            definition: defObj.definition,
            example: defObj.example,
            source: 'dictionaryapi',
          };
          definitionCache.set(word, result);
          return result;
        }
      }
    }
  } catch {
    // Fall through to Datamuse fast API
  }

  // 2. Fallback to Datamuse Fast Lexical API (`api.datamuse.com`)
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2500);
    const res = await fetch(
      `https://api.datamuse.com/words?sp=${word.toLowerCase()}&md=dp&max=1`,
      { signal: controller.signal }
    );
    clearTimeout(timeout);

    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0 && data[0].word?.toUpperCase() === word) {
        const item = data[0];
        if (Array.isArray(item.defs) && item.defs.length > 0) {
          const [rawPos, ...defParts] = item.defs[0].split('\t');
          const posMap: Record<string, string> = {
            n: 'noun',
            v: 'verb',
            adj: 'adjective',
            adv: 'adverb',
          };
          const result: WordDefinition = {
            word,
            partOfSpeech: posMap[rawPos] || 'word',
            definition: defParts.join(' '),
            source: 'datamuse',
          };
          definitionCache.set(word, result);
          return result;
        }
      }
    }
  } catch {
    // Ignore network error and check CORE_DICTIONARY
  }

  if (CORE_DICTIONARY.has(word)) {
    const fallback = getCuratedFallback(word);
    definitionCache.set(word, fallback);
    return fallback;
  }

  return null;
}

/**
 * Scoring system based on word length (inspired by Squaredle / Squares.org / Boggle)
 */
export function calculateWordScore(word: string, isFeaturedWord: boolean = false): number {
  const len = word.length;
  let base = 1;
  if (len === 4) base = 1;
  else if (len === 5) base = 2;
  else if (len === 6) base = 4;
  else if (len === 7) base = 7;
  else if (len === 8) base = 11;
  else if (len >= 9) base = 16 + (len - 9) * 5;

  return isFeaturedWord ? base + 5 : base;
}

export interface RankTier {
  name: string;
  minPct: number;
  badge: string;
}

export const RANK_TIERS: RankTier[] = [
  { name: 'Novice Seeker', minPct: 0, badge: 'I' },
  { name: 'Tile Apprentice', minPct: 10, badge: 'II' },
  { name: 'Space Finder', minPct: 25, badge: 'III' },
  { name: 'Pattern Weaver', minPct: 45, badge: 'IV' },
  { name: 'Golden Architect', minPct: 68, badge: 'V' },
  { name: 'Grand Saboteur', minPct: 88, badge: 'VI' },
  { name: 'The Missing Piece', minPct: 100, badge: '★' },
];

export function getPlayerRank(progressPct: number): {
  current: RankTier;
  next: RankTier | null;
} {
  let current = RANK_TIERS[0];
  let next: RankTier | null = RANK_TIERS[1];

  for (let i = 0; i < RANK_TIERS.length; i++) {
    if (progressPct >= RANK_TIERS[i].minPct) {
      current = RANK_TIERS[i];
      next = RANK_TIERS[i + 1] || null;
    }
  }
  return { current, next };
}
